def linear(hex_colour):
    """sRGB hex to linear RGBA, which is what Blender's colour sockets take."""
    out = []
    for i in (0, 2, 4):
        c = int(hex_colour[i : i + 2], 16) / 255
        out.append(c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4)
    return (*out, 1.0)
