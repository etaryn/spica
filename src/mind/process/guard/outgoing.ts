/**
 * Every outgoing message passes through here: replies, reach-outs, backchannels and the busy
 * note. With the guard on, a flagged candidate gets one regeneration with a corrective note,
 * then a fallback line. With the guard off (the test phase, so her full range can be observed),
 * the first candidate goes out unchecked and one judge_log row records that nothing was checked.
 */
import { insertJudgeLogs, type GuardOutcome, type NewJudgeLog } from "@/db/repos/user/judge-log";
import type { Deps } from "@/mind/platform/deps";
import { errorName } from "@/mind/platform/errors";
import { withTimeout } from "@/mind/platform/timeout";
import { hasSafety } from "./categories";
import { correctiveNote, fallbackLine } from "./fallback";
import { checkMessage, type GuardInput, type GuardVerdict } from "./guard";
import { matchKeyword } from "./keywords";

export type OutgoingArgs = {
  userId: string;
  /** The user turn being answered (judge_log.turn_id and the fallback seed); null when there is none. */
  turnId: string | null;
  input: Omit<GuardInput, "text">;
  /** The first candidate, generated by the caller. */
  first: string;
  regenerate?: (correction: string) => Promise<string>;
};

/** `writeLog` is deferred: the caller writes judge_log after the message is sent. */
export type OutgoingResult = { text: string; outcome: GuardOutcome; writeLog: () => Promise<void> };

type Checked = { text: string; verdict: GuardVerdict };
type GuardDeps = Pick<Deps, "db" | "llm" | "config" | "clock" | "log">;

export async function guardOutgoing(deps: GuardDeps, args: OutgoingArgs): Promise<OutgoingResult> {
  if (!deps.config.guard.enabled) {
    const text = args.first.trim();
    return { text, outcome: "guard_disabled", writeLog: () => writeDisabledLog(deps, args, text) };
  }

  const checked: Checked[] = [];
  const check = async (text: string) => {
    const verdict = await checkMessage(deps, { ...args.input, text });
    checked.push({ text, verdict });
    return verdict;
  };
  const send = (text: string, outcome: GuardOutcome): OutgoingResult => ({
    text,
    outcome,
    writeLog: () => writeLog(deps, args, checked, outcome),
  });
  const fallback = () =>
    fallbackLine(
      deps.config,
      args.input.kind === "crisis_reply" ? "crisis_reply" : "reply",
      args.turnId,
    );

  // A few words can't carry a threat or an invented detail the keyword list would miss, so
  // backchannels and busy notes skip the model. A hit drops the message rather than sending a
  // fallback line.
  if (args.input.kind === "backchannel" || args.input.kind === "availability") {
    const text = args.first.trim();
    const hit = matchKeyword(text, deps.config.guard.fallback_keywords);
    checked.push({ text, verdict: keywordVerdict(hit) });
    return hit ? send("", "fallback") : send(text, "passed");
  }

  const firstDraft = args.first.trim();
  const firstVerdict = await check(firstDraft);
  if (firstVerdict.ok) {
    return send(firstDraft, firstVerdict.source === "model" ? "passed" : "guard_unavailable");
  }
  if (firstVerdict.source === "keyword_fallback") return send(fallback(), "fallback");

  // Without a second draft: a safety problem falls back, an honesty-only one is sent as is.
  const keepFirstOrFallBack = () =>
    hasSafety(firstVerdict.violations)
      ? send(fallback(), "fallback")
      : send(firstDraft, "sent_with_violation");

  if (!args.regenerate) return keepFirstOrFallBack();

  let secondDraft: string;
  try {
    const correction = correctiveNote(deps.config, firstVerdict.violations);
    secondDraft = (await args.regenerate(correction)).trim();
  } catch (e) {
    deps.log.error("guard regeneration failed", {
      userId: args.userId,
      turnId: args.turnId,
      error: errorName(e),
    });
    return keepFirstOrFallBack();
  }

  const secondVerdict = await check(secondDraft);
  if (secondVerdict.ok) {
    return send(
      secondDraft,
      secondVerdict.source === "model" ? "regenerated" : "guard_unavailable",
    );
  }
  // The guard went down for the second draft, so its keyword hit only speaks to that draft. The
  // first was model-checked: if its problems were honesty-only it's known safe to send.
  if (secondVerdict.source === "keyword_fallback") return keepFirstOrFallBack();

  if (hasSafety(secondVerdict.violations)) return send(fallback(), "fallback");
  // The second draft is safe but still has honesty problems.
  if (hasSafety(firstVerdict.violations)) return send(secondDraft, "sent_with_violation");

  const fewerProblems =
    firstVerdict.violations.length < secondVerdict.violations.length ? firstDraft : secondDraft;
  return send(fewerProblems, "sent_with_violation");
}

function keywordVerdict(hit: string | null): GuardVerdict {
  return {
    ok: !hit,
    violations: hit ? [{ category: "threat", claim: hit }] : [],
    source: "keyword_fallback",
    reasoning: null,
    latencyMs: 0,
    error: null,
    promptVersion: "keywords",
  };
}

/**
 * The log row never stores memory content: recalled and onboarding facts are logged by id and
 * subject only. The guard call itself still gets the content; only the log is stripped, and
 * only here, so that rule has one place to hold.
 */
function logInput(input: OutgoingArgs["input"], text: string) {
  return {
    kind: input.kind,
    recentTurns: input.recentTurns,
    recalledFacts: input.recalledFacts.map((f) => ({ id: f.id, subject: f.subject })),
    onboardingFacts: input.onboardingFacts.map((f) => ({ id: f.id })),
    text,
  };
}

/** One row per checked candidate, with the outcome on the last. Bounded and best effort. */
async function writeLog(
  deps: Pick<Deps, "db" | "config" | "clock" | "log">,
  args: OutgoingArgs,
  checked: Checked[],
  outcome: GuardOutcome,
): Promise<void> {
  const at = deps.clock.now();
  const rows: NewJudgeLog[] = checked.map((candidate, i) => ({
    kind: "guard",
    turn_id: args.turnId,
    attempt: i + 1,
    input: logInput(args.input, candidate.text),
    output:
      candidate.verdict.source === "model"
        ? { reasoning: candidate.verdict.reasoning, violations: candidate.verdict.violations }
        : { error: candidate.verdict.error, keyword_violations: candidate.verdict.violations },
    outcome: i === checked.length - 1 ? outcome : null,
    source: candidate.verdict.source,
    latency_ms: candidate.verdict.latencyMs,
    model: candidate.verdict.promptVersion === "keywords" ? "keywords" : deps.config.models.guard,
    prompt_version: candidate.verdict.promptVersion,
    created_at: at,
  }));

  await insertLogRows(deps, args, rows);
}

async function writeDisabledLog(
  deps: Pick<Deps, "db" | "config" | "clock" | "log">,
  args: OutgoingArgs,
  text: string,
): Promise<void> {
  const row: NewJudgeLog = {
    kind: "guard",
    turn_id: args.turnId,
    attempt: 1,
    input: logInput(args.input, text),
    output: {},
    outcome: "guard_disabled",
    source: "disabled",
    latency_ms: 0,
    model: "none",
    prompt_version: "disabled",
    created_at: deps.clock.now(),
  };

  await insertLogRows(deps, args, [row]);
}

/** Never fails the message: a slow or broken log write is only logged. */
async function insertLogRows(
  deps: Pick<Deps, "db" | "config" | "log">,
  args: OutgoingArgs,
  rows: NewJudgeLog[],
): Promise<void> {
  try {
    await withTimeout(
      Promise.resolve().then(() => insertJudgeLogs(deps.db, args.userId, rows)),
      deps.config.guard.log_timeout_ms,
    );
  } catch (e) {
    deps.log.error("judge_log write failed", {
      userId: args.userId,
      turnId: args.turnId,
      error: errorName(e),
    });
  }
}
