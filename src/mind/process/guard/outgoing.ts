/**
 * Every outgoing message passes through here: replies, reach-outs, backchannels and the busy
 * note. With the guard on, a flagged candidate is never regenerated, so a structural problem
 * stays visible: a safety problem gets a fallback line, an honesty-only one is sent as is. With the guard switched off, the first candidate goes out unchecked and
 * one judge_log row records that nothing was checked.
 */
import { insertJudgeLogs, type GuardOutcome, type NewJudgeLog } from "@/db/repos/user/judge-log";
import type { Deps } from "@/mind/platform/deps";
import { errorName } from "@/mind/platform/errors";
import { withTimeout } from "@/mind/platform/timeout";
import { hasSafety, type Category, type Pointed } from "./categories";
import { fallbackLine } from "./fallback";
import { checkMessage, type GuardInput, type GuardVerdict } from "./guard";
import { matchKeyword } from "./keywords";
import { groundSelfClaims, isUngrounded, type GroundedClaim } from "./self-claims";

export type OutgoingArgs = {
  userId: string;
  /** The user turn being answered (judge_log.turn_id and the fallback seed); null when there is none. */
  turnId: string | null;
  input: Omit<GuardInput, "text">;
  /** The only candidate, generated by the caller. */
  first: string;
};

/** `writeLog` is deferred: the caller writes judge_log after the message is sent. */
export type OutgoingResult = {
  text: string;
  outcome: GuardOutcome;
  /** The allowed pointed remark the sent message carries, stored so it counts once per occasion. */
  pointed: Pointed | null;
  writeLog: () => Promise<void>;
};

type Checked = { text: string; verdict: GuardVerdict; claims: GroundedClaim[] };
type GuardDeps = Pick<Deps, "db" | "llm" | "config" | "clock" | "log" | "embedder" | "core">;

export async function guardOutgoing(deps: GuardDeps, args: OutgoingArgs): Promise<OutgoingResult> {
  if (!deps.config.guard.enabled) {
    const text = args.first.trim();
    return {
      text,
      outcome: "guard_disabled",
      pointed: null,
      writeLog: () => writeDisabledLog(deps, args, text),
    };
  }

  const checked: Checked[] = [];
  const check = async (text: string) => {
    const raw = await checkMessage(deps, { ...args.input, text });
    const claims = await groundSelfClaims(deps, args.input, raw.selfClaims, {
      userId: args.userId,
      turnId: args.turnId,
    });
    // Its own threshold: a claim said in passing paraphrases the memory loosely, so it matches
    // lower than the cold path's stored facts do.
    const invented = claims
      .filter((c) => isUngrounded(c, deps.config.guard.self_claim_similarity))
      .map((c) => ({ category: "invented_self" as const, claim: c.claim }));
    const verdict = invented.length
      ? { ...raw, ok: false, violations: [...raw.violations, ...invented] }
      : raw;
    checked.push({ text, verdict, claims });
    return verdict;
  };
  const send = (text: string, outcome: GuardOutcome): OutgoingResult => ({
    text,
    outcome,
    // Only the sent candidate's own model verdict may tag it; a fallback line or an outage tags nothing.
    pointed:
      checked.findLast((c) => c.text === text && c.verdict.source === "model")?.verdict.pointed ??
      null,
    writeLog: () => writeLog(deps, args, checked, outcome),
  });
  const fallback = () =>
    fallbackLine(
      deps.config,
      args.input.kind === "crisis_reply" ? "crisis_reply" : "reply",
      args.turnId,
    );

  // A few words can't carry a threat or an invented detail the keyword list would miss, so
  // backchannels and busy notes skip the model. A hit drops the message rather than sending a
  // fallback line.
  if (args.input.kind === "backchannel" || args.input.kind === "availability") {
    const text = args.first.trim();
    const hit = matchKeyword(text, deps.config.guard.fallback_keywords);
    checked.push({ text, verdict: keywordVerdict(hit), claims: [] });
    return hit ? send("", "fallback") : send(text, "passed");
  }

  const draft = args.first.trim();
  const verdict = await check(draft);
  if (verdict.ok) {
    return send(draft, verdict.source === "model" ? "passed" : "guard_unavailable");
  }
  if (verdict.source === "keyword_fallback") return send(fallback(), "fallback");

  // Writing first is optional: a reach-out with the day wrong isn't sent at all.
  if (args.input.kind === "reach_out" && verdict.violations.some((v) => v.category === "wrong_day"))
    return send("", "dropped");
  // A safety problem falls back; an honesty-only one is sent as is.
  return hasSafety(verdict.violations)
    ? send(fallback(), "fallback")
    : send(draft, "sent_with_violation");
}

function keywordVerdict(hit: { category: string; phrase: string } | null): GuardVerdict {
  return {
    ok: !hit,
    violations: hit ? [{ category: hit.category as Category, claim: hit.phrase }] : [],
    selfClaims: [],
    pointed: null,
    source: "keyword_fallback",
    reasoning: null,
    latencyMs: 0,
    error: null,
    promptVersion: "keywords",
  };
}

/**
 * The log row never stores memory content: recalled and onboarding facts are logged by id and
 * subject only. The guard call itself still gets the content; only the log is stripped, and
 * only here, so that rule has one place to hold.
 */
function logInput(input: OutgoingArgs["input"], text: string) {
  return {
    kind: input.kind,
    recentTurns: input.recentTurns,
    recalledFacts: input.recalledFacts.map((f) => ({ id: f.id, subject: f.subject })),
    onboardingFacts: input.onboardingFacts.map((f) => ({ id: f.id })),
    usedOnOccasion: input.usedOnOccasion,
    text,
  };
}

/** One row per checked candidate, with the outcome on the last. Bounded and best effort. */
async function writeLog(
  deps: Pick<Deps, "db" | "config" | "clock" | "log">,
  args: OutgoingArgs,
  checked: Checked[],
  outcome: GuardOutcome,
): Promise<void> {
  const at = deps.clock.now();
  const rows: NewJudgeLog[] = checked.map((candidate, i) => ({
    kind: "guard",
    turn_id: args.turnId,
    attempt: i + 1,
    input: logInput(args.input, candidate.text),
    output:
      candidate.verdict.source === "model"
        ? {
            reasoning: candidate.verdict.reasoning,
            violations: candidate.verdict.violations,
            self_claims: candidate.claims,
            pointed: candidate.verdict.pointed,
          }
        : { error: candidate.verdict.error, keyword_violations: candidate.verdict.violations },
    outcome: i === checked.length - 1 ? outcome : null,
    source: candidate.verdict.source,
    latency_ms: candidate.verdict.latencyMs,
    model: candidate.verdict.promptVersion === "keywords" ? "keywords" : deps.config.models.guard,
    prompt_version: candidate.verdict.promptVersion,
    created_at: at,
  }));

  await insertLogRows(deps, args, rows);
}

async function writeDisabledLog(
  deps: Pick<Deps, "db" | "config" | "clock" | "log">,
  args: OutgoingArgs,
  text: string,
): Promise<void> {
  const row: NewJudgeLog = {
    kind: "guard",
    turn_id: args.turnId,
    attempt: 1,
    input: logInput(args.input, text),
    output: {},
    outcome: "guard_disabled",
    source: "disabled",
    latency_ms: 0,
    model: "none",
    prompt_version: "disabled",
    created_at: deps.clock.now(),
  };

  await insertLogRows(deps, args, [row]);
}

/** Never fails the message: a slow or broken log write is only logged. */
async function insertLogRows(
  deps: Pick<Deps, "db" | "config" | "log">,
  args: OutgoingArgs,
  rows: NewJudgeLog[],
): Promise<void> {
  try {
    await withTimeout(
      Promise.resolve().then(() => insertJudgeLogs(deps.db, args.userId, rows)),
      deps.config.guard.log_timeout_ms,
    );
  } catch (e) {
    deps.log.error("judge_log write failed", {
      userId: args.userId,
      turnId: args.turnId,
      error: errorName(e),
    });
  }
}
